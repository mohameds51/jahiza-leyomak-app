import assert from 'node:assert/strict';
import {compareTrials,validTrial,progressCalm,messageTemplates} from './experience.ts';
const a={id:'a',kind:'hair',date:'2026-12-01',provider:'',notes:'',rating:4,favorite:false,imageIds:[]};
const b={...a,id:'b',kind:'makeup'};
assert.equal(validTrial(a),true);
assert.equal(validTrial({...a,rating:6}),false);
assert.equal(validTrial({...a,imageIds:['1','2','3','4']}),false);
assert.deepEqual(compareTrials([a,b],['b','a']).map(x=>x.id),['b','a']);
assert.equal(progressCalm([{id:'a',date:'2026-12-01',done:true},{id:'b',date:'2026-12-02',done:true}], '2026-12-01'),1);
assert.equal(messageTemplates.length,3);
console.log('Experience tests passed (6 assertions)');
